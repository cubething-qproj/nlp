"""Data sets: plain texts with standoff annotations, the concept registry, and gold-labelled notes.

A data set directory (see README) loads into a `DataSet`. Each `Text` is a
plain `.txt` file plus an optional sibling `.json` holding a W3C Web
Annotation `AnnotationPage`. We read a small subset of that model: each
`Annotation` tags one or more concept ids (bodies with purpose `tagging`) onto
one or more `Target` ranges, and may carry a non-standard `layer` naming what
kind of structure it is. Annotations may overlap freely. Tier 0 scores a
highlight against them by coverage (`Text.concepts_at`).

Each `Note` points into a text by `span` over its plain text and carries its
`Gold` labels. Loading fails only on unreadable files or annotations missing
required structure; everything else is reported by `DataSet.problems`, so one
run of `notelab check` lists every mistake at once.
"""

from __future__ import annotations

import json
import tomllib
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

SPLITS = ("dev", "holdout")


@dataclass(frozen=True)
class Target:
    """One range `[start, end)` of a text, in code points (W3C `TextPositionSelector`).

    `exact`, `prefix` and `suffix` come from an optional `TextQuoteSelector`;
    when present they are checked against the text, so offsets that drift
    after a text edit are caught.
    """

    source: str
    start: int
    end: int
    exact: str | None = None
    prefix: str | None = None
    suffix: str | None = None

    @classmethod
    def from_json(cls, row: dict) -> Target:
        selectors = {s["type"]: s for s in as_list(row["selector"])}
        if "TextPositionSelector" not in selectors:
            raise ValueError(f"target on {row['source']!r} has no TextPositionSelector")
        position, quote = selectors["TextPositionSelector"], selectors.get("TextQuoteSelector", {})
        return cls(
            row["source"], position["start"], position["end"],
            quote.get("exact"), quote.get("prefix"), quote.get("suffix"),
        )

    def problems(self, plain: str) -> list[str]:
        """Mismatches between this target and the text it points into."""
        where = f"range [{self.start}, {self.end})"
        # DEFERRED: non-int offsets (e.g. "start": "3" or 2.5) raise TypeError in this comparison and crash `check`
        # instead of being reported; a missing start/end key likewise KeyErrors in from_json.
        # Annotation JSON is generated by the labelling pipeline, not hand-written.
        if not 0 <= self.start < self.end <= len(plain):
            return [f"{where} is outside the text (length {len(plain)})"]
        checks = [
            ("exact", self.exact, plain[self.start : self.end]),
            ("prefix", self.prefix, plain[max(0, self.start - len(self.prefix or "")) : self.start]),
            ("suffix", self.suffix, plain[self.end : self.end + len(self.suffix or "")]),
        ]
        return [
            f"{where}: {name} {expected!r} does not match text {actual!r}"
            for name, expected, actual in checks
            if expected is not None and expected != actual
        ]


@dataclass(frozen=True)
class Annotation:
    """Concept ids tagged onto one or more ranges (a W3C `Annotation`).

    Several targets express a passage that is interrupted or split; several
    tagging bodies express a passage about several concepts. Bodies with other
    purposes are ignored for now.
    """

    id: str
    layer: str | None
    concepts: frozenset[str]
    targets: tuple[Target, ...]

    @classmethod
    def from_json(cls, row: dict) -> Annotation:
        bodies = as_list(row.get("body", []))
        return cls(
            row["id"],
            row.get("layer"),
            frozenset(b["value"] for b in bodies if b.get("purpose") == "tagging"),
            tuple(Target.from_json(t) for t in as_list(row["target"])),
        )


@dataclass(frozen=True)
class Text:
    """A source text: `plain` is what the player reads; `annotations` point into it."""

    name: str
    file: str
    plain: str
    annotations: tuple[Annotation, ...]

    @classmethod
    def load(cls, path: Path) -> Text:
        """Read `path` and, if it exists, its sibling `.json` annotation page."""
        page = path.with_suffix(".json")
        items = json.loads(page.read_text(encoding="utf-8"))["items"] if page.exists() else []
        # No newline translation: offsets must match the file as Rust reads it.
        plain = path.read_text(encoding="utf-8", newline="")
        return cls(path.stem, path.name, plain, tuple(Annotation.from_json(a) for a in items))

    def concepts_at(self, start: int, end: int, layer: str | None = None) -> dict[str, float]:
        """Tier 0: each concept's share of the highlight `[start, end)` covered by its ranges.

        Overlapping ranges of one concept count once. `layer` restricts to one
        layer; `None` uses all of them. An empty highlight covers nothing.
        """
        if end <= start:
            return {}
        clipped: dict[str, list[tuple[int, int]]] = {}
        for annotation in self.annotations:
            if layer is not None and annotation.layer != layer:
                continue
            for t in annotation.targets:
                lo, hi = max(t.start, start), min(t.end, end)
                if lo < hi:
                    for concept in annotation.concepts:
                        clipped.setdefault(concept, []).append((lo, hi))
        return {c: covered_length(ranges) / (end - start) for c, ranges in clipped.items()}


@dataclass(frozen=True)
class Concept:
    """One thing the game can react to; `label` and `description` are what models see."""

    id: str
    label: str
    description: str
    synonyms: tuple[str, ...] = ()


@dataclass(frozen=True)
class Gold:
    """The hand-written answer for a note: concept ids, stance (or none), slot values."""

    concepts: frozenset[str]
    stance: str | None
    slots: dict[str, str] = field(default_factory=dict)


@dataclass(frozen=True)
class Note:
    """A player note attached to the span `[start, end)` of text `source`.

    `highlight`, if given, must equal that span's plain text; it exists so
    notes stay readable and offsets that drift after a text edit are caught.
    """

    id: str
    split: str
    text: str
    source: str
    span: tuple[int, int]
    highlight: str | None
    gold: Gold

    @classmethod
    def from_json(cls, row: dict) -> Note:
        source, gold = row["source"], row["gold"]
        return cls(
            id=row["id"],
            split=row["split"],
            text=row["text"],
            source=source["text"],
            # DEFERRED: a malformed span is not validated until note_problems unpacks it; see the comment there.
            span=tuple(source["span"]),
            highlight=source.get("highlight"),
            gold=Gold(frozenset(gold["concepts"]), gold.get("stance"), gold.get("slots", {})),
        )


@dataclass(frozen=True)
class DataSet:
    """Everything in one data set directory; see the module docs for the layout."""

    texts: dict[str, Text]
    concepts: dict[str, Concept]
    stances: tuple[str, ...]
    slots: tuple[str, ...]
    notes: tuple[Note, ...]

    @classmethod
    def load(cls, root: Path) -> DataSet:
        registry = tomllib.loads((root / "concepts.toml").read_text())
        concepts = {
            id_: Concept(id_, c["label"], c["description"], tuple(c.get("synonyms", ())))
            for id_, c in registry["concepts"].items()
        }
        texts = {path.stem: Text.load(path) for path in sorted((root / "texts").glob("*.txt"))}
        lines = (root / "notes.jsonl").read_text().splitlines()
        notes = tuple(Note.from_json(json.loads(line)) for line in lines if line.strip())
        return cls(texts, concepts, tuple(registry["stances"]), tuple(registry["slots"]), notes)

    def problems(self) -> list[str]:
        """Every inconsistency in the set, one message each; empty means usable."""
        return (
            [p for t in self.texts.values() for p in self.text_problems(t)]
            + [f"note {id_}: duplicate id" for id_ in duplicates(n.id for n in self.notes)]
            + [f"note {n.id}: {p}" for n in self.notes for p in self.note_problems(n)]
        )

    def text_problems(self, text: Text) -> list[str]:
        where = f"text {text.name}"
        problems = [f"{where}: duplicate annotation id {id_!r}" for id_ in duplicates(a.id for a in text.annotations)]
        for a in text.annotations:
            at = f"{where} annotation {a.id}"
            if not a.concepts:
                problems.append(f"{at}: no tagging body")
            problems += [f"{at}: concept {c!r} is not a concept" for c in sorted(a.concepts - self.concepts.keys())]
            for t in a.targets:
                if t.source != text.file:
                    problems.append(f"{at}: target source {t.source!r} is not {text.file!r}")
                problems += [f"{at}: {p}" for p in t.problems(text.plain)]
        return problems

    def note_problems(self, note: Note) -> list[str]:
        problems = []
        if note.split not in SPLITS:
            problems.append(f"split {note.split!r} is not one of {SPLITS}")
        problems += [f"gold concept {c!r} is not a concept" for c in sorted(note.gold.concepts - self.concepts.keys())]
        if note.gold.stance is not None and note.gold.stance not in self.stances:
            problems.append(f"gold stance {note.gold.stance!r} is not one of {self.stances}")
        problems += [f"gold slot {s!r} is not one of {self.slots}" for s in note.gold.slots if s not in self.slots]
        text = self.texts.get(note.source)
        if text is None:
            return problems + [f"source text {note.source!r} does not exist"]
        # DEFERRED: a span of the wrong length (e.g. [5]) or with non-int values crashes `check` here instead of
        # being reported. Annotation JSON is generated by the labelling pipeline, not hand-written.
        start, end = note.span
        if not 0 <= start < end <= len(text.plain):
            return problems + [f"span {list(note.span)} is outside text {note.source!r} (length {len(text.plain)})"]
        if note.highlight is not None and text.plain[start:end] != note.highlight:
            problems.append(f"span {list(note.span)} reads {text.plain[start:end]!r}, not highlight {note.highlight!r}")
        return problems


def as_list(value: dict | list) -> list:
    """W3C lets most properties be one object or an array of them."""
    return value if isinstance(value, list) else [value]


def covered_length(ranges: list[tuple[int, int]]) -> int:
    """Total length of the union of half-open ranges."""
    total, reach = 0, None
    for lo, hi in sorted(ranges):
        if reach is None or lo >= reach:
            total += hi - lo
            reach = hi
        elif hi > reach:
            total += hi - reach
            reach = hi
    return total


def duplicates(ids) -> list[str]:
    """Ids occurring more than once, sorted."""
    return sorted(id_ for id_, k in Counter(ids).items() if k > 1)
